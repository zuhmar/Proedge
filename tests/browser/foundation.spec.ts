import {test,expect} from '@playwright/test';
test('dashboard filtering, matchup detail, navigation and responsive layout',async({page},testInfo)=>{
 const failures:string[]=[];page.on('pageerror',error=>failures.push(error.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Your edge starts here.'})).toBeVisible();
 await expect(page.locator('.game-card')).toHaveCount(4);
 await expect(page.locator('.demo-banner')).toContainText('Fictional');
 await page.getByRole('button',{name:'NBA',exact:true}).filter({visible:true}).last().click();
 await expect(page.locator('.game-card')).toHaveCount(2);
 await page.getByRole('textbox',{name:'Search teams'}).fill('Harbor');
 await expect(page.locator('.game-card')).toHaveCount(1);
 await page.getByRole('button',{name:'View matchup'}).click();
 await expect(page.getByRole('dialog')).toContainText('FICTIONAL DEMO');
 await expect(page.getByRole('dialog')).toContainText('Matchup data unavailable');
 await page.getByRole('button',{name:'Close matchup'}).click();
 await page.getByRole('textbox',{name:'Search teams'}).fill('does-not-exist');
 await expect(page.getByRole('heading',{name:'No games for these filters'})).toBeVisible();
 await page.getByRole('textbox',{name:'Search teams'}).fill('');
 if(testInfo.project.name==='mobile') await page.getByRole('button',{name:'More',exact:true}).click();
 await page.getByRole('button',{name:'Player Props',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Player projections are not available yet'})).toBeVisible();
 await page.getByRole('button',{name:'Show data source status'}).click();
 await expect(page.getByRole('heading',{name:'Data source monitoring'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 expect(failures).toEqual([]);
 await page.screenshot({path:`/tmp/proedge-${testInfo.project.name}.png`,fullPage:true});
});

test('account registration, persistent watchlist, preferences and logout',async({page},testInfo)=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Sign in',exact:true}).first().click();
 await page.getByRole('button',{name:'New here? Create an account'}).click();
 const email=`browser-${testInfo.project.name}-${Date.now()}@example.com`;
 await page.getByRole('textbox',{name:'Email',exact:true}).fill(email);
 await page.getByLabel('Password',{exact:false}).fill('secure-browser-password-2026');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:/Save Metro Sparks versus Harbor Waves/}).click();
 await expect(page.getByRole('status')).toContainText('Game saved');
 await page.getByRole('button',{name:'Watchlist',exact:true}).filter({visible:true}).first().click();
 await expect(page.locator('.game-card')).toHaveCount(1);
 await page.reload();
 await page.getByRole('button',{name:'Watchlist',exact:true}).filter({visible:true}).first().click();
 await expect(page.locator('.game-card')).toHaveCount(1);
 if(testInfo.project.name==='mobile') await page.getByRole('button',{name:'More',exact:true}).click();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('combobox',{name:'Timezone',exact:true}).selectOption('UTC');
 await page.getByRole('button',{name:'Save preferences'}).click();
 await expect(page.getByRole('status')).toContainText('Preferences saved');
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sign in',exact:true}).first()).toBeVisible();
});
